async function writeProject(root: string, files: CodeFile[]) {
  for (const file of files) {
    const target = join(root, file.name)
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, file.content, 'utf8')
  }
}

describe('codeAgenticLargeProjectProof', () => {
  test('executor WS3 genere un mini SaaS >40 fichiers buildable et teste', async () => {
    const proofFiles = buildProofFiles()
    const queue = buildGenerationQueueFromArchitecturePlan(architecturePlanFor(proofFiles))
    assert.ok(queue)
    assert.equal(queue.items.length > 40, true)

    const result = await executeCodeGenerationQueue({
      queue,
      nextMeta: nextMetaFactory(),
      produceActions: async ({ item }) => {
        const content = proofFiles.get(item.path)
        assert.equal(typeof content, 'string')
        return [{ kind: 'write_file', path: item.path, language: item.language ?? undefined, content }]
      },
    })

    assert.equal(result.ok, true)
    assert.equal(result.files.length, proofFiles.size)
    assert.equal(result.files.length > 40, true)
    assert.equal(result.events.at(-1)?.kind, 'done')

    const root = await mkdtemp(join(tmpdir(), 'aurora-ws3-large-proof-'))
    try {
      await writeProject(root, result.files)
      const build = execFileSync('npm', ['run', 'build', '--silent'], { cwd: root, encoding: 'utf8', timeout: 20_000 })
      const tests = execFileSync('npm', ['test', '--silent'], { cwd: root, encoding: 'utf8', timeout: 20_000 })
      assert.match(build, /build-check ok 32 entities/)
      assert.match(tests, /auth register\/login\/permissions/)
      assert.match(tests, /crud services cover all generated entities/)
    } finally {
      await rm(root, { recursive: true, force: true })
    }
  })
})
